CREATE SCHEMA IF NOT EXISTS dimensional;

-- ============================================================================
-- 1. HIERARQUIA GEOGRÁFICA (Snowflake)
-- ============================================================================

-- 1.1 Dim_Regiao
CREATE TABLE dimensional.dim_regiao (
    id_regiao      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_regiao    VARCHAR(20) NOT NULL,
    CONSTRAINT uq_dim_regiao_nome UNIQUE (nome_regiao)
);

COMMENT ON TABLE dimensional.dim_regiao IS 'Regiões do Brasil: Norte, Nordeste, Sudeste, Sul, Centro-Oeste';
COMMENT ON COLUMN dimensional.dim_regiao.nome_regiao IS 'Norte, Nordeste, Sudeste, Sul, Centro-Oeste';

-- 1.2 Dim_UF
CREATE TABLE dimensional.dim_uf (
    id_uf          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_uf        VARCHAR(50) NOT NULL,
    sigla_uf       CHAR(2) NOT NULL,
    id_regiao      INTEGER NOT NULL REFERENCES dimensional.dim_regiao(id_regiao) ON DELETE RESTRICT,
    CONSTRAINT uq_dim_uf_sigla UNIQUE (sigla_uf),
    CONSTRAINT uq_dim_uf_nome UNIQUE (nome_uf)
);

CREATE INDEX idx_dim_uf_id_regiao ON dimensional.dim_uf(id_regiao);

COMMENT ON TABLE dimensional.dim_uf IS 'Unidades da Federação';

-- 1.3 Dim_Municipio
CREATE TABLE dimensional.dim_municipio (
    id_municipio       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_ibge        VARCHAR(7) NOT NULL,
    nome_municipio     VARCHAR(100) NOT NULL,
    id_uf              INTEGER NOT NULL REFERENCES dimensional.dim_uf(id_uf) ON DELETE RESTRICT,
    CONSTRAINT uq_dim_municipio_codigo UNIQUE (codigo_ibge)
);

CREATE INDEX idx_dim_municipio_id_uf ON dimensional.dim_municipio(id_uf);
CREATE INDEX idx_dim_municipio_nome ON dimensional.dim_municipio(nome_municipio);

COMMENT ON TABLE dimensional.dim_municipio IS 'Municípios brasileiros (código IBGE 7 dígitos)';
COMMENT ON COLUMN dimensional.dim_municipio.codigo_ibge IS 'Código IBGE de 7 dígitos';

