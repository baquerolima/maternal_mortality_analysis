-- ============================================================================
-- 5. Dim_Tempo
-- ============================================================================
CREATE TABLE dimensional.dim_tempo (
    id_tempo        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data_completa   DATE NOT NULL,
    dia             INTEGER NOT NULL,
    mes             INTEGER NOT NULL,
    ano             INTEGER NOT NULL,
    trimestre       INTEGER NOT NULL,
    semestre        INTEGER NOT NULL,
    CONSTRAINT uq_dim_tempo_data UNIQUE (data_completa),
    CONSTRAINT chk_dim_tempo_dia CHECK (dia BETWEEN 1 AND 31),
    CONSTRAINT chk_dim_tempo_mes CHECK (mes BETWEEN 1 AND 12),
    CONSTRAINT chk_dim_tempo_trimestre CHECK (trimestre BETWEEN 1 AND 4),
    CONSTRAINT chk_dim_tempo_semestre CHECK (semestre BETWEEN 1 AND 2)
);

CREATE INDEX idx_dim_tempo_ano ON dimensional.dim_tempo(ano);
CREATE INDEX idx_dim_tempo_ano_mes ON dimensional.dim_tempo(ano, mes);

COMMENT ON TABLE dimensional.dim_tempo IS 'Dimensão calendário (2014-2023+)';

