COMMENT ON TABLE dimensional.dim_cid IS 'Classificação CID-10 (role-playing: causa_basica, causa_materna, causa_basica_original)';

-- ============================================================================
-- 15. TABELA FATO: Fact_MorteMaterna
-- ============================================================================
CREATE TABLE dimensional.fact_morte_materna (
    id_tempo                     INTEGER NOT NULL REFERENCES dimensional.dim_tempo(id_tempo) ON DELETE RESTRICT,
    id_municipio_ocorrencia      INTEGER NOT NULL REFERENCES dimensional.dim_municipio(id_municipio) ON DELETE RESTRICT,
    id_municipio_residencia      INTEGER REFERENCES dimensional.dim_municipio(id_municipio) ON DELETE RESTRICT,
    id_municipio_estabelecimento INTEGER REFERENCES dimensional.dim_municipio(id_municipio) ON DELETE RESTRICT,
    id_bairro_ocorrencia         INTEGER REFERENCES dimensional.dim_bairro(id_bairro) ON DELETE RESTRICT,
    id_estabelecimento_saude     INTEGER REFERENCES dimensional.dim_estabelecimento_saude(id_estabelecimento) ON DELETE RESTRICT,
    id_faixa_etaria              INTEGER REFERENCES dimensional.dim_faixa_etaria(id_faixa_etaria) ON DELETE RESTRICT,
    id_raca_cor                  INTEGER REFERENCES dimensional.dim_raca_cor(id_raca_cor) ON DELETE RESTRICT,
    id_local_ocorrencia          INTEGER REFERENCES dimensional.dim_local_ocorrencia(id_local_ocorrencia) ON DELETE RESTRICT,
    id_situacao_gestacional      INTEGER REFERENCES dimensional.dim_situacao_gestacional_obito(id_situacao_gestacional) ON DELETE RESTRICT,
    id_tipo_parto                INTEGER REFERENCES dimensional.dim_tipo_parto(id_tipo_parto) ON DELETE RESTRICT,
    id_momento_obito_parto       INTEGER REFERENCES dimensional.dim_momento_obito_parto(id_momento_obito_parto) ON DELETE RESTRICT,
    id_tipo_gravidez             INTEGER REFERENCES dimensional.dim_tipo_gravidez(id_tipo_gravidez) ON DELETE RESTRICT,
    id_semana_gestacao           INTEGER REFERENCES dimensional.dim_semana_gestacao(id_semana_gestacao) ON DELETE RESTRICT,
    id_causa_basica              INTEGER NOT NULL REFERENCES dimensional.dim_cid(id_cid) ON DELETE RESTRICT,
    id_causa_materna             INTEGER REFERENCES dimensional.dim_cid(id_cid) ON DELETE RESTRICT,
    id_causa_basica_original     INTEGER REFERENCES dimensional.dim_cid(id_cid) ON DELETE RESTRICT,
    sexo                         CHAR(1),
    recebeu_assistencia_medica   BOOLEAN,
    quantidade_obitos            INTEGER NOT NULL DEFAULT 1,
    -- Chave primária composta: grão = combinação única de dimensões
    CONSTRAINT pk_fact_morte_materna PRIMARY KEY (
        id_tempo,
        id_municipio_ocorrencia,
        id_causa_basica,
        COALESCE(id_municipio_residencia, 0),
        COALESCE(id_municipio_estabelecimento, 0),
        COALESCE(id_bairro_ocorrencia, 0),
        COALESCE(id_estabelecimento_saude, 0),
        COALESCE(id_faixa_etaria, 0),
        COALESCE(id_raca_cor, 0),
        COALESCE(id_local_ocorrencia, 0),
        COALESCE(id_situacao_gestacional, 0),
        COALESCE(id_tipo_parto, 0),
        COALESCE(id_momento_obito_parto, 0),
        COALESCE(id_tipo_gravidez, 0),
        COALESCE(id_semana_gestacao, 0),
        COALESCE(id_causa_materna, 0),
        COALESCE(id_causa_basica_original, 0),
        COALESCE(sexo, 'X'),
        COALESCE(recebeu_assistencia_medica::INTEGER, -1)::BOOLEAN
    ),
    CONSTRAINT chk_fact_sexo CHECK (sexo IN ('F', 'M', 'I'))
);

-- Índices para performance analítica
CREATE INDEX idx_fact_morte_tempo           ON dimensional.fact_morte_materna(id_tempo);
CREATE INDEX idx_fact_morte_municipio_oc    ON dimensional.fact_morte_materna(id_municipio_ocorrencia);
CREATE INDEX idx_fact_morte_municipio_res   ON dimensional.fact_morte_materna(id_municipio_residencia);
CREATE INDEX idx_fact_morte_causa_basica    ON dimensional.fact_morte_materna(id_causa_basica);
CREATE INDEX idx_fact_morte_causa_materna   ON dimensional.fact_morte_materna(id_causa_materna);
CREATE INDEX idx_fact_morte_faixa_etaria    ON dimensional.fact_morte_materna(id_faixa_etaria);
CREATE INDEX idx_fact_morte_raca_cor        ON dimensional.fact_morte_materna(id_raca_cor);
CREATE INDEX idx_fact_morte_estabelecimento ON dimensional.fact_morte_materna(id_estabelecimento_saude);
CREATE INDEX idx_fact_morte_sexo            ON dimensional.fact_morte_materna(sexo);

COMMENT ON TABLE dimensional.fact_morte_materna IS 'Fato de mortalidade materna — grão: combinação única de dimensões. measure: quantidade_obitos (COUNT)';
COMMENT ON COLUMN dimensional.fact_morte_materna.sexo IS 'F=Feminino, M=Masculino, I=Ignorado. Normalizado no ETL.';
COMMENT ON COLUMN dimensional.fact_morte_materna.quantidade_obitos IS 'Medida: contagem de óbitos para aquela combinação de dimensões';

-- ============================================================================
-- 16. TABELA DE METADADOS: dim_carga (tracking de ETL)
-- ============================================================================
CREATE TABLE dimensional.dim_carga (
    id_carga       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_tabela    VARCHAR(100) NOT NULL,
    tipo_operacao  VARCHAR(20) NOT NULL,  -- 'FULL_REFRESH', 'INCREMENTAL'
    status         VARCHAR(20) NOT NULL DEFAULT 'PENDENTE',  -- 'PENDENTE', 'EM_EXECUCAO', 'CONCLUIDO', 'ERRO'
    registros_inseridos  INTEGER DEFAULT 0,
    registros_atualizados INTEGER DEFAULT 0,
    registros_excluidos   INTEGER DEFAULT 0,
    mensagem_erro    TEXT,
    iniciado_em     TIMESTAMP WITH TIME ZONE,
    finalizado_em   TIMESTAMP WITH TIME ZONE,
    criado_em       TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    CONSTRAINT chk_dim_carga_operacao CHECK (tipo_operacao IN ('FULL_REFRESH', 'INCREMENTAL')),
    CONSTRAINT chk_dim_carga_status CHECK (status IN ('PENDENTE', 'EM_EXECUCAO', 'CONCLUIDO', 'ERRO'))
);

CREATE INDEX idx_dim_carga_tabela ON dimensional.dim_carga(nome_tabela);
CREATE INDEX idx_dim_carga_status ON dimensional.dim_carga(status);

COMMENT ON TABLE dimensional.dim_carga IS 'Metadados de carga das dimensões — auditoria de quando cada tabela foi populada';

