-- ============================================================================
-- 3. Dim_EstabelecimentoSaude
-- ============================================================================
CREATE TABLE dimensional.dim_estabelecimento_saude (
    id_estabelecimento          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_cnes                 VARCHAR(7) NOT NULL,
    nome_estabelecimento        VARCHAR(255),
    id_municipio                INTEGER REFERENCES dimensional.dim_municipio(id_municipio) ON DELETE RESTRICT,
    id_natureza_organizacao     INTEGER REFERENCES dimensional.dim_natureza_organizacao(id_natureza_organizacao) ON DELETE RESTRICT,
    id_tipo_gestao              INTEGER REFERENCES dimensional.dim_tipo_gestao(id_tipo_gestao) ON DELETE RESTRICT,
    id_nivel_hierarquia         INTEGER REFERENCES dimensional.dim_nivel_hierarquia(id_nivel_hierarquia) ON DELETE RESTRICT,
    id_esfera_administrativa    INTEGER REFERENCES dimensional.dim_esfera_administrativa(id_esfera_administrativa) ON DELETE RESTRICT,
    id_tipo_unidade             INTEGER REFERENCES dimensional.dim_tipo_unidade(id_tipo_unidade) ON DELETE RESTRICT,
    id_natureza_juridica        INTEGER REFERENCES dimensional.dim_natureza_juridica(id_natureza_juridica) ON DELETE RESTRICT,
    st_centro_obstetrico        BOOLEAN DEFAULT FALSE,
    st_centro_neonatal          BOOLEAN DEFAULT FALSE,
    st_atend_hospitalar         BOOLEAN DEFAULT FALSE,
    st_servico_apoio            BOOLEAN DEFAULT FALSE,
    st_atend_ambulatorial       BOOLEAN DEFAULT FALSE,
    co_motivo_desab             VARCHAR(20),
    co_ambulatorial_sus         VARCHAR(20),
    CONSTRAINT uq_dim_estabelecimento_cnes UNIQUE (codigo_cnes)
);

CREATE INDEX idx_dim_estabelecimento_id_municipio ON dimensional.dim_estabelecimento_saude(id_municipio);
CREATE INDEX idx_dim_estabelecimento_id_natureza ON dimensional.dim_estabelecimento_saude(id_natureza_organizacao);
CREATE INDEX idx_dim_estabelecimento_id_gestao ON dimensional.dim_estabelecimento_saude(id_tipo_gestao);
CREATE INDEX idx_dim_estabelecimento_nome ON dimensional.dim_estabelecimento_saude(nome_estabelecimento);

COMMENT ON TABLE dimensional.dim_estabelecimento_saude IS 'Estabelecimentos de saúde (CNES), com sub-dimensões snowflake';

-- ============================================================================
